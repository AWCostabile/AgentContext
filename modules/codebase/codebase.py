#!/usr/bin/env python3
"""codebase.py: regenerate a knowledge tree's generated `codebase/` tier from a repository.

The tier is a code map: the repository's source areas and file counts, the surfaces it is
entered through, and one symbols leaf per source area. This script is the tier's only
writer. The codebase.*.md leaves and the Contents rows of the branch's .index.md are its
output; the prose above the Contents table, .tags and .agent are authored and only ever
created when absent (.agent on request).

Honest output: every location is a `path:line` code span; a file no selected extractor
claims, and anything an extractor could not read, is listed under "Not extracted"; names
only, never the value of a constant, a string or an environment variable; extracted text
is neutralised so it forms neither a link nor a template placeholder; every leaf is sorted
and deterministic, and the one `_generated:_` provenance line is the only part that varies
between runs over the same source, so --check ignores it and a rerun over unchanged source
rewrites nothing.

Python 3.10+, standard library only. Exit 0 clean, 1 drift or a failure, 2 a usage error
or a refusal (nothing written).
"""
import argparse
import datetime
import fnmatch
import json
import os
import re
import subprocess
import sys

sys.dont_write_bytecode = True   # the module directory stays as committed
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from extractors import EXTRACTORS, claimant, claims                    # noqa: E402
from extractors.common import read_source                              # noqa: E402

TOOL_VERSION = 1
LEAF_LIMIT = 110                 # lines a leaf may reach before it is split into parts
GENERATED = '_generated:_'
RESERVED = ('map', 'surfaces')   # leaf names an area may not take
SKIP_DIRS = ('node_modules', 'vendor', 'dist', 'build')
SURFACE_KINDS = ('entry-points', 'exports-per-area', 'exports-of', 'env-keys')
DEFAULT_SURFACES = {'entry-points': True, 'exports-per-area': True}
LIST_CAP = 10                    # paths shown per "Not extracted" group
NAMES_CAP = 30                   # names shown per area in the exports-per-area surface
LEAF_RE = re.compile(r'^codebase\.([a-z0-9][a-z0-9-]*)(?:\.([0-9]+))?\.md$')
ARCHIVED_RE = re.compile(r'^_status:_\s*archived\b')
SLUG_RE = re.compile(r'^[a-z0-9][a-z0-9-]*$')
ELLIPSIS = chr(0x2026)
EXTRACTED = ('Generated by `codebase.py` from the source: never hand-edit it; regenerate with the command '
             'the branch\'s `.agent` names.')


class Refusal(Exception):
    """A usage error or a refusal: reported, exit 2, nothing written."""


class Report:
    def __init__(self):
        self.fails = 0

    def ok(self, m): print('[ OK ] ' + m)
    def info(self, m): print('[INFO] ' + m)
    def warn(self, m): print('[WARN] ' + m)

    def fail(self, m):
        print('[FAIL] ' + m)
        self.fails += 1


# --- markdown ----------------------------------------------------------------------------

def neutralize(s):
    """Extracted text that can form neither a link nor a placeholder, on one line."""
    s = re.sub(r'\s*\n\s*', ' ', str(s))
    return s.replace('](', '] (').replace('{{', '{\\{').replace('}}', '}\\}')


def code(s):
    s = neutralize(s)
    ticks = '`'
    while ticks in s:
        ticks += '`'
    pad = ' ' if s.startswith('`') or s.endswith('`') else ''
    return '%s%s%s%s%s' % (ticks, pad, s, pad, ticks)


def cell(s):
    return s.replace('|', '\\|')


def table(columns, rows):
    out = ['| ' + ' | '.join(columns) + ' |', '| ' + ' | '.join('-' * max(3, len(c)) for c in columns) + ' |']
    out += ['| ' + ' | '.join(cell(c) for c in r) + ' |' for r in rows]
    return out


def loc(path, line=None):
    return code('%s:%d' % (path, line) if line else path)


def plural(n, one, many=None):
    return '%d %s' % (n, one if n == 1 else (many or one + 's'))


def byte_key(s):
    return s.encode('utf-8')


# --- the repository ----------------------------------------------------------------------

def git(repo, *args):
    try:
        p = subprocess.run(['git', '-C', repo] + list(args), capture_output=True)
    except OSError:
        return None
    return p.stdout.decode('utf-8', 'replace') if p.returncode == 0 else None


def identify(repo):
    """{name, basename, sha, git}: the repository's name and its commit, when under git."""
    base = os.path.basename(os.path.normpath(repo))
    top = git(repo, 'rev-parse', '--show-toplevel')
    if top is None:
        return {'name': base, 'basename': base, 'sha': None, 'git': False}
    top = os.path.normcase(os.path.normpath(top.strip()))
    name = base
    if top == os.path.normcase(os.path.normpath(repo)):
        common = (git(repo, 'rev-parse', '--path-format=absolute', '--git-common-dir') or '').strip()
        if common and os.path.basename(os.path.normpath(common)) == '.git':
            name = os.path.basename(os.path.dirname(os.path.normpath(common)))   # a worktree's main name
    sha = (git(repo, 'rev-parse', '--short=7', 'HEAD') or '').strip() or None
    return {'name': name, 'basename': base, 'sha': sha, 'git': True}


def skipped(rel):
    parts = rel.split('/')
    return any(p.startswith('.') or p in SKIP_DIRS for p in parts)


def file_set(repo, ident):
    """Every file of the repository, relative and sorted: under git, what `git ls-files`
    lists (tracked, and untracked but not ignored); otherwise a walk. Either way, hidden
    paths and the SKIP_DIRS directories are left out, so both modes agree."""
    files = set()
    out = git(repo, 'ls-files', '-co', '--exclude-standard', '-z') if ident['git'] else None
    if out is not None:
        for p in out.split('\0'):
            p = p.replace('\\', '/')
            if p and not skipped(p) and os.path.isfile(os.path.join(repo, p)):
                files.add(p)
    else:
        for d, dirs, names in os.walk(repo):
            dirs[:] = [x for x in dirs if not x.startswith('.') and x not in SKIP_DIRS]
            for n in names:
                rel = os.path.relpath(os.path.join(d, n), repo).replace(os.sep, '/')
                if not skipped(rel):
                    files.add(rel)
    return sorted(files, key=byte_key)


def load_profile(path):
    if path is None:
        return {}
    try:
        profile = json.loads(read_source(path))
    except (OSError, UnicodeDecodeError, ValueError) as e:
        raise Refusal('--profile %s could not be read as JSON (%s)' % (path, e))
    if not isinstance(profile, dict):
        raise Refusal('--profile: the top level must be an object')
    extra = sorted(set(profile) - {'name', 'areas', 'surfaces'})
    if extra:
        raise Refusal('--profile: unknown key(s) %s; the keys are name, areas, surfaces' % ', '.join(extra))
    if 'name' in profile and not (isinstance(profile['name'], str) and profile['name'].strip()):
        raise Refusal('--profile: name must be a non-empty string')
    areas = profile.get('areas', [])
    if not isinstance(areas, list):
        raise Refusal('--profile: areas must be a list')
    seen = set()
    for a in areas:
        if not isinstance(a, dict) or set(a) != {'name', 'paths'}:
            raise Refusal('--profile: each area is {"name": …, "paths": […]}')
        if not isinstance(a['name'], str) or not SLUG_RE.match(a['name']) or a['name'] in RESERVED:
            raise Refusal('--profile: area name %r must be lowercase [a-z0-9-] and not one of %s'
                          % (a['name'], ', '.join(RESERVED)))
        if a['name'] in seen:
            raise Refusal('--profile: area %s is named twice' % a['name'])
        seen.add(a['name'])
        if not isinstance(a['paths'], list) or not a['paths'] or not all(isinstance(p, str) and p for p in a['paths']):
            raise Refusal('--profile: area %s needs a non-empty list of paths' % a['name'])
    surfaces = profile.get('surfaces', DEFAULT_SURFACES)
    if not isinstance(surfaces, dict):
        raise Refusal('--profile: surfaces must be an object keyed by surface kind')
    extra = sorted(set(surfaces) - set(SURFACE_KINDS))
    if extra:
        raise Refusal('--profile: unknown surface kind(s) %s; the kinds are %s' % (', '.join(extra), ', '.join(SURFACE_KINDS)))
    for k, v in surfaces.items():
        if k == 'exports-of':
            if not isinstance(v, list) or not all(isinstance(p, str) for p in v):
                raise Refusal('--profile: surfaces.exports-of must be a list of paths')
        elif not isinstance(v, bool):
            raise Refusal('--profile: surfaces.%s must be true or false' % k)
    return profile


def slugify(s):
    return re.sub(r'-+', '-', re.sub(r'[^a-z0-9]', '-', s.lower())).strip('-') or 'area'


def assign_areas(sources, profile):
    """area slug -> {paths: [display], files: [rel]}: the profile's areas by longest path
    prefix, then each remaining file by its top-level directory (`root` for root files)."""
    rules = []
    for a in profile.get('areas', []):
        for p in a['paths']:
            rules.append((p.replace('\\', '/').lstrip('./'), a['name']))
    rules.sort(key=lambda r: -len(r[0]))
    areas = {}
    for a in profile.get('areas', []):
        areas[a['name']] = {'paths': list(a['paths']), 'files': []}
    for rel in sources:
        name = next((n for p, n in rules if rel == p or (p.endswith('/') and rel.startswith(p))), None)
        if name is None:
            top = rel.split('/')[0] if '/' in rel else None
            name = slugify(top) if top else 'root'
            if name in RESERVED:
                name += '-dir'
            shown = top + '/' if top else '(repository root files)'
            entry = areas.setdefault(name, {'paths': [], 'files': []})
            if shown not in entry['paths']:
                entry['paths'].append(shown)
        areas[name]['files'].append(rel)
    return areas


# --- leaves and parts --------------------------------------------------------------------

def section(title, body):
    """A leaf section: its heading and body lines, and where its table starts (or None)."""
    start = next((i for i, l in enumerate(body) if l.startswith('| ')), None)
    return {'title': title, 'body': body, 'table': start}


def paginate(sections, header_size, footer):
    """Sections packed into parts of at most LEAF_LIMIT lines; a section too long for a part
    of its own continues its table into the next part under a `(continued)` heading."""
    room = LEAF_LIMIT - header_size
    pieces = []
    for s in sections:
        lines = ['', '## ' + s['title'], ''] + s['body']
        if len(lines) <= room or s['table'] is None:
            pieces.append(lines)
            continue
        head = ['', '## ' + s['title'], ''] + s['body'][:s['table'] + 2]
        th = s['body'][s['table']:s['table'] + 2]
        rows = s['body'][s['table'] + 2:]
        cur, first = head, True
        for r in rows:
            if len(cur) + 1 > room:
                pieces.append(cur)
                cur = ['', '## %s (continued)' % s['title'], ''] + th
                first = False
            cur.append(r)
        pieces.append(cur)
    parts, cur = [], []
    for p in pieces:
        if cur and len(cur) + len(p) > room:
            parts.append(cur)
            cur = []
        cur += p
    if cur and len(cur) + len(footer) > room:
        parts.append(cur)
        cur = []
    parts.append(cur + footer)
    return parts


def build_leaf(slug, h1, gen, legend, sections, notes):
    """{filename: (h1, text)} for one leaf, split into parts when it would pass LEAF_LIMIT."""
    footer = ['', '## Not extracted', ''] + (['- ' + n for n in notes] if notes else ['Nothing.'])
    header_size = 4 + len(legend) + 1
    parts = paginate(sections, header_size, footer)
    out = {}
    for k, body in enumerate(parts, 1):
        fn = 'codebase.%s.md' % slug if k == 1 else 'codebase.%s.%d.md' % (slug, k)
        title = h1 if k == 1 else '%s, part %d' % (h1, k)
        lead = legend if k == 1 else (['Part %d of %d; the first part is `codebase.%s.md`, which says what these '
                                       'tables hold.' % (k, len(parts), slug)] + [EXTRACTED]
                                      + [''] * (len(legend) - 2))[:len(legend)]
        text = '\n'.join(['# ' + title, '', gen, ''] + lead + body) + '\n'
        out[fn] = (title, re.sub(r'\n{3,}', '\n\n', text))
    return out


# --- rendering ---------------------------------------------------------------------------

def symbol_label(s):
    name = '%s.%s' % (s['parent'], s['name']) if s['parent'] else s['name']
    sig = s.get('signature') or ''
    if not sig:
        return name
    if s['kind'] in ('function', 'method', 'constructor') and sig[:1] in '(<[':
        return name + sig
    return name + ' ' + sig


def ordered(symbols):
    """[(key, symbol)] in source order, a member placed after its parent when the parent is
    in the same file (a Go method declared below other types still follows its type)."""
    top = {}
    for s in symbols:
        if s['parent'] is None:
            top.setdefault(s['name'], s['line'])

    def key(s):
        if s['parent'] is not None and s['parent'] in top:
            return (top[s['parent']], 1, s['line'])
        return (s['line'], 0, 0)
    return sorted(((key(s), s) for s in symbols), key=lambda t: t[0])


def file_notes(rel, f):
    if f['error']:
        return ['%s: %s.' % (code(rel), f['error'])]
    return ['%s: %s.' % (code(rel), n) for n in f['notes']]


def export_row(e):
    """(name, kind, line, summary) of one export that is not a declaration."""
    if e['source']:
        what = 'from %s' % code(e['source'])
        if e.get('local'):
            what = '%s %s' % (code(e['local']), what)
        return (e['name'], 're-export', e['line'], what)
    if e.get('local'):
        return (e['name'], 'export', e['line'], 'exports %s under this name' % code(e['local']))
    return (e['name'], 'export', e['line'], 'no local declaration was found')


def exported_names(f):
    names = [(s['name'], s['kind'], s['line'], neutralize(s['summary'])) for s in f['symbols']
             if s['parent'] is None and s['exported']]
    return names + [export_row(e) for e in f['exports']]


def render_area(ctx, slug, area):
    files = area['files']
    secs, notes, symbols = [], [], 0
    for rel in files:
        f = ctx['facts'][rel]
        notes += file_notes(rel, f)
        if f['error']:
            continue
        body = []
        lead = []
        doc = f['module_doc']
        if f['package'] and not re.match(r'^\w+ %s\b' % re.escape(f['package']), doc):
            lead.append('Package %s.' % code(f['package']))
        if doc:
            lead.append(neutralize(doc))
        if lead:
            body += [' '.join(lead), '']
        imports = list(dict.fromkeys(i['source'] for i in f['imports']))
        if imports:
            shown = ', '.join(code(i) for i in imports[:12])
            more = ' and %d more' % (len(imports) - 12) if len(imports) > 12 else ''
            body += ['Imports: %s%s.' % (shown, more), '']
        keyed = [(k, [code(symbol_label(s)), s['kind'], 'yes' if s['exported'] else 'no', loc(rel, s['line']),
                      neutralize(s['summary'])]) for k, s in ordered(f['symbols'])]
        for e in f['exports']:
            name, kind, line, what = export_row(e)
            keyed.append(((line, 0, 0), [code(name), kind, 'yes', loc(rel, line), what]))
        rows = [r for _, r in sorted(keyed, key=lambda t: t[0])]
        symbols += len(rows)
        if rows:
            body += table(['Symbol', 'Kind', 'Exported', 'Location', 'Summary'], rows)
        else:
            body.append('No declaration was found in this file.')
        secs.append(section(code(rel), body))
    where = ', '.join(code(p) for p in area['paths'])
    legend = ['Declarations of the `%s` area (%s), one section per file in path order: the top-level ones, '
              'exported or not, and a type\'s members as `Type.member`; a summary is the first sentence of the '
              'declaration\'s doc comment.' % (slug, where), EXTRACTED]
    h1 = '%s — symbols: %s' % (ctx['name'], slug)
    leaves = build_leaf(slug, h1, ctx['gen'], legend, secs, notes)
    purpose = 'declarations in %s — %s in %s' % (', '.join(area['paths']), plural(symbols, 'symbol'),
                                                 plural(len(files), 'file'))
    return leaves, purpose, symbols


def render_surfaces(ctx):
    kinds = ctx['surfaces']
    secs, notes, counts = [], [], []
    facts, sources = ctx['facts'], ctx['sources']
    if kinds.get('entry-points'):
        rows = []
        for e in ctx['entries']:
            rows.append((e['path'], e['line'] or 0, [code(e['name']), e['kind'], loc(e['path'], e['line'])]))
        for rel in sources:
            for e in facts[rel]['entry']:
                name = rel.rsplit('/', 1)[0] + '/' if e['kind'] == 'Go main package' and '/' in rel else rel
                rows.append((rel, e['line'], [code(name), e['kind'], loc(rel, e['line'])]))
        rows.sort(key=lambda r: (byte_key(r[0]), r[1], r[2][0]))
        body = (['Where the repository starts running: the root package file\'s `main`, `module`, `bin` and the '
                 'scripts that run a source file (by name, never the command), a Go `main` package, and an '
                 'executable script.', ''] + table(['Entry', 'Kind', 'Location'], [r[2] for r in rows])) if rows \
            else ['No entry point was found.']
        secs.append(section('Entry points', body))
        counts.append(plural(len(rows), 'entry point'))
    if kinds.get('exports-per-area'):
        rows, total = [], 0
        for slug in sorted(ctx['areas']):
            names = []
            for rel in ctx['areas'][slug]['files']:
                names += [n for n, _, _, _ in exported_names(facts[rel]) if n != '*']
            names = sorted(set(names), key=byte_key)
            total += len(names)
            shown = ', '.join(code(n) for n in names[:NAMES_CAP])
            if len(names) > NAMES_CAP:
                shown += ' and %d more (see `codebase.%s.md`)' % (len(names) - NAMES_CAP, slug)
            rows.append([code(slug), str(len(names)), shown or '—'])
        secs.append(section('Exported names per area', ['Distinct top-level names each area exports, sorted.', '']
                            + table(['Area', 'Names', 'Exported'], rows)))
        counts.append(plural(total, 'exported name'))
    for rel in kinds.get('exports-of', []):
        if rel not in facts:
            notes.append('%s is named by the profile\'s `exports-of` but is not a source file any selected '
                         'extractor read.' % code(rel))
            continue
        names = exported_names(facts[rel])
        rows = [[code(n), k, loc(rel, line), summary] for n, k, line, summary in sorted(names, key=lambda x: x[2])]
        body = table(['Name', 'Kind', 'Location', 'Summary'], rows) if rows else ['The file exports nothing.']
        secs.append(section('Exports of %s' % code(rel), body))
        counts.append('%s of %s' % (plural(len(rows), 'export'), rel))
    if kinds.get('env-keys'):
        reads = {}
        for rel in sources:
            for e in facts[rel]['env']:
                reads.setdefault(e['name'], []).append((rel, e['line']))
        rows = []
        for name in sorted(reads, key=byte_key):
            at = sorted(set(reads[name]), key=lambda t: (byte_key(t[0]), t[1]))
            shown = ', '.join(loc(p, l) for p, l in at[:5])
            if len(at) > 5:
                shown += ' and %d more' % (len(at) - 5)
            rows.append([code(name), shown])
        body = (['Environment variable NAMES the source reads; values are never extracted.', '']
                + table(['Name', 'Read at'], rows)) if rows else ['No environment variable read was found.']
        secs.append(section('Environment variables', body))
        counts.append(plural(len(rows), 'environment name'))
    if not secs:
        secs.append(section('Surfaces', ['The profile asks for no surface.']))
    legend = ['How %s is entered and what it exposes, as the profile asks: %s.'
              % (ctx['name'], ', '.join(k for k in SURFACE_KINDS if kinds.get(k)) or 'nothing'), EXTRACTED]
    h1 = '%s — surfaces' % ctx['name']
    purpose = 'entry points and exposed names — ' + (', '.join(counts) or 'none asked for')
    return build_leaf('surfaces', h1, ctx['gen'], legend, secs, notes), purpose


def render_map(ctx, area_symbols):
    facts, files, sources = ctx['facts'], ctx['files'], ctx['sources']
    ident = ['- **Repository:** ' + neutralize(ctx['name'])]
    for label, value in ctx['identity']:
        ident.append('- **%s:** %s' % (label, code(value)))
    used = []
    for name in sorted(ctx['selected']):
        n = sum(1 for rel in sources if facts[rel]['extractor'] == name)
        if n:
            used.append('%s (%s) — %s' % (code(name), EXTRACTORS[name]['language'], plural(n, 'file')))
    ident.append('- **Extracted by:** ' + ('; '.join(used) if used else 'no extractor matched a file'))
    ident.append('- **Areas from:** ' + ('the profile, then the top-level directories'
                                         if ctx['profile'].get('areas') else 'the top-level directories'))
    rows = []
    for slug in sorted(ctx['areas']):
        a = ctx['areas'][slug]
        rows.append([code(slug), ', '.join(code(p) for p in a['paths']), str(len(a['files'])),
                     str(area_symbols[slug]), code('codebase.%s.md' % slug)])
    area_body = ['Each area\'s source files and the leaf listing their declarations.', '']
    area_body += table(['Area', 'Paths', 'Source files', 'Symbols', 'Leaf'], rows) if rows \
        else ['No source file was found.']

    notes = list(ctx['identity_notes'])
    for rel in sources:
        notes += file_notes(rel, facts[rel])
    groups = {}
    for rel in files:
        if rel in facts:
            continue
        other = claimant(rel)
        if other is not None:
            key = ('extractor', other['name'])
        else:
            base = rel.rsplit('/', 1)[-1]
            ext = os.path.splitext(base)[1].lower() if '.' in base[1:] else ''
            key = ('ext', ext)
        groups.setdefault(key, []).append(rel)
    for key in sorted(groups):
        ps = groups[key]
        shown = ', '.join(code(p) for p in ps[:LIST_CAP])
        if len(ps) > LIST_CAP:
            shown += ' and %d more' % (len(ps) - LIST_CAP)
        if key[0] == 'extractor':
            why = 'runs only when named with `--lang`' if EXTRACTORS[key[1]]['default'] is False \
                else 'was not named with `--lang`'
            notes.append('%s claimed by the %s extractor, which %s, so listed and not symbolised: %s.'
                         % (plural(len(ps), 'file'), code(key[1]), why, shown))
        else:
            label = code('*' + key[1]) if key[1] else 'no extension'
            notes.append('%s — %s, no extractor: %s.' % (label, plural(len(ps), 'file'), shown))
    secs = [section('Identity', ident), section('Areas', area_body)]
    legend = ['The areas, languages and file counts of %s, and every file no extractor read.' % ctx['name'], EXTRACTED]
    h1 = '%s — code map' % ctx['name']
    purpose = 'areas, languages and file counts — %s, %s, %s' % (
        plural(len(files), 'file'), plural(len(sources), 'source file'), plural(len(ctx['areas']), 'area'))
    return build_leaf('map', h1, ctx['gen'], legend, secs, notes), purpose


def render(ctx):
    """[(base filename, {filename: (h1, text)}, purpose)] in Contents order."""
    out, area_symbols = [], {}
    areas = []
    for slug in sorted(ctx['areas']):
        leaves, purpose, n = render_area(ctx, slug, ctx['areas'][slug])
        area_symbols[slug] = n
        areas.append(('codebase.%s.md' % slug, leaves, purpose))
    leaves, purpose = render_map(ctx, area_symbols)
    out.append(('codebase.map.md', leaves, purpose))
    leaves, purpose = render_surfaces(ctx)
    out.append(('codebase.surfaces.md', leaves, purpose))
    return out + areas


# --- the branch directory ----------------------------------------------------------------

def strip_generated(text):
    return [l for l in text.split('\n') if not l.startswith(GENERATED)]


def h1_of(text):
    return next((l[2:].strip() for l in text.split('\n') if l.startswith('# ')), None)


def index_row(h1, fn, purpose, parts=(), archived=False):
    link = '[%s%s](./%s)' % (h1.replace('|', '\\|'), ' _(archived)_' if archived else '', fn)
    more = ''
    if parts:
        more = '; continued in ' + ', '.join('[part %d](./%s)' % (k, p) for k, p in parts)
    return '| %s | %s%s |' % (link, purpose.replace('|', '\\|'), more)


def contents_bounds(lines):
    """(first data row, end) of the table under `## Contents`, (insert at, insert at) when
    the heading has no table yet, or None without the heading."""
    head = next((i for i, l in enumerate(lines) if re.match(r'^##\s+Contents\s*$', l.rstrip())), None)
    if head is None:
        return None
    i = head + 1
    while i < len(lines) and not lines[i].startswith('|') and not lines[i].startswith('#'):
        i += 1
    if i + 1 < len(lines) and lines[i].startswith('|') and re.match(r'^\|\s*:?-', lines[i + 1]):
        j = i + 2
        while j < len(lines) and lines[j].startswith('|'):
            j += 1
        return i + 2, j
    return None if i < len(lines) and lines[i].startswith('|') else (-1, head + 1)


def rewrite_index(text, rows):
    eol = '\r\n' if '\r\n' in text else '\n'
    lines = text.split(eol)
    b = contents_bounds(lines)
    if b is None:
        return None
    start, end = b
    if start == -1:
        return eol.join(lines[:end] + ['', '| File | Purpose |', '| ---- | ------- |'] + rows + lines[end:])
    return eol.join(lines[:start] + rows + lines[end:])


def current_rows(text):
    lines = text.replace('\r\n', '\n').split('\n')
    b = contents_bounds(lines)
    if b is None:
        return None
    return [] if b[0] == -1 else [l.rstrip() for l in lines[b[0]:b[1]]]


def scaffold_index(name):
    return ('# %s code base\n\n'
            'The code of %s as a generated map: its areas and file counts, the surfaces it is entered\n'
            'through, and one symbols leaf per source area. Every leaf and every Contents row below is\n'
            'written by `codebase.py`; read `.agent` before touching this branch.\n\n'
            '## Contents\n\n| File | Purpose |\n| ---- | ------- |\n' % (name, name))


TAGS = 'codebase\ncode-map\ngenerated\nsymbols\n'


def agent_text(command):
    return ('Generated tier. Every codebase.*.md leaf and every Contents row of .index.md is written by\n'
            'codebase.py: never hand-edit them; fix the generator or the source and regenerate. The prose\n'
            'above the Contents table, .tags and this file are authored.\n\n'
            'Regenerate when the change that moved the source lands, never for an unmerged branch, from\n'
            'the directory this command was first run in:\n\n'
            '    %s\n\n'
            'Add --check to report drift without writing; the _generated:_ line never counts as drift.\n'
            % command)


def archived_stub(h1, today):
    return ('# %s\n\n_status:_ archived %s — the source no longer has this area, so codebase.py no longer writes it\n\n'
            'This leaf was generated for an area the repository no longer holds.\n'
            'It is kept rather than deleted so that a citation of it keeps resolving;\n'
            'nothing regenerates it, and its Contents row is marked archived.\n' % (h1, today))


def write(path, text):
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)


def first_difference(disk, want):
    a, b = strip_generated(disk.replace('\r\n', '\n')), strip_generated(want)
    if a == b:
        return None
    for i in range(max(len(a), len(b))):
        x = a[i] if i < len(a) else '(end of file)'
        y = b[i] if i < len(b) else '(end of file)'
        if x != y:
            return 'tier "%s" / source "%s"' % (x[:90], y[:90])
    return 'line endings'


def command_line(argv_paths, args):
    """The regenerate command, its paths relative to the working directory."""
    def rel(p):
        try:
            r = os.path.relpath(os.path.abspath(p))
        except ValueError:
            return os.path.abspath(p).replace('\\', '/')
        return r.replace('\\', '/')
    parts = ['python', rel(argv_paths), '--repo', rel(args.repo), '--into', rel(args.into)]
    for name in args.lang or []:
        parts += ['--lang', name]
    if args.profile:
        parts += ['--profile', rel(args.profile)]
    return ' '.join(parts)


