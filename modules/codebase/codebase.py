HELP_EPILOG = """\
extractors: %s
profile:    {"name": "Product", "areas": [{"name": "server", "paths": ["server/"]}],
             "surfaces": {"entry-points": true, "exports-per-area": true,
                          "exports-of": ["src/index.ts"], "env-keys": true}}
exit:       0 clean, 1 drift or a failure, 2 a usage error or a refusal
"""


def parse(argv):
    names = ', '.join(n if EXTRACTORS[n]['default'] else n + ' (only when named)' for n in sorted(EXTRACTORS))
    ap = argparse.ArgumentParser(
        prog='codebase.py', formatter_class=argparse.RawDescriptionHelpFormatter,
        description='Regenerate the generated codebase/ tier of a knowledge tree from a repository: a code map, '
                    'the surfaces, and one symbols leaf per source area.',
        epilog=HELP_EPILOG % names)
    ap.add_argument('--repo', required=True, help='the repository root to read (git optional)')
    ap.add_argument('--into', required=True, help='the tier directory, <tree>/public/<catalog>/<Product>/codebase')
    ap.add_argument('--lang', action='append', metavar='NAME',
                    help='run only this extractor; repeatable (default: every extractor that runs by default)')
    ap.add_argument('--profile', metavar='FILE', help='a JSON file naming the areas and the surfaces to list')
    ap.add_argument('--check', action='store_true', help='report drift against --into and write nothing')
    ap.add_argument('--write-agent', action='store_true', help='write the tier\'s .agent with this command')
    return ap.parse_args(argv)


def inside(child, parent):
    c = os.path.normcase(os.path.realpath(child))
    p = os.path.normcase(os.path.realpath(parent))
    try:
        return os.path.commonpath([c, p]) == p
    except ValueError:
        return False


def main(argv):
    try:
        sys.stdout.reconfigure(encoding='utf-8', errors='replace')
    except (AttributeError, ValueError):
        pass
    args = parse(argv)
    report = Report()
    try:
        return run(args, report)
    except Refusal as e:
        print('[FAIL] ' + str(e))
        return 2


def run(args, report):
    repo, into = os.path.abspath(args.repo), os.path.abspath(args.into)
    if not os.path.isdir(repo):
        raise Refusal('--repo %s is not a directory' % args.repo)
    if inside(into, repo):
        raise Refusal('--into %s is inside --repo: the generator never writes into the repository it reads' % args.into)
    if os.path.exists(into) and not os.path.isdir(into):
        raise Refusal('--into %s exists and is not a directory' % args.into)
    unknown = sorted(set(args.lang or []) - set(EXTRACTORS))
    if unknown:
        raise Refusal('--lang %s: unknown; the extractors are %s' % (', '.join(unknown), ', '.join(sorted(EXTRACTORS))))
    selected = set(args.lang) if args.lang else {n for n, e in EXTRACTORS.items() if e['default']}
    profile = load_profile(args.profile)
    if args.check and not os.path.isdir(into):
        raise Refusal('--into %s does not exist: nothing to check' % args.into)

    ident = identify(repo)
    files = file_set(repo, ident)
    facts = {}
    for rel in files:
        e = claimant(rel, selected)
        if e is not None:
            f = e['module'].extract(repo, rel)
            f['extractor'] = e['name']
            facts[rel] = f
    sources = [rel for rel in files if rel in facts]
    identity, identity_notes, entries = [], [], []
    for name in sorted(selected):
        mod = EXTRACTORS[name]['module']
        mine = [rel for rel in sources if facts[rel]['extractor'] == name]
        if not mine:
            continue
        if hasattr(mod, 'identity'):
            lines, notes = mod.identity(repo, files)
            identity += [l for l in lines if l not in identity]
            identity_notes += [n for n in notes if n not in identity_notes]
        if hasattr(mod, 'entries'):
            entries += [e for e in mod.entries(repo, files) if e not in entries]
    today = datetime.date.today().isoformat()
    gen = '%s %s from %s @ %s · codebase.py %d' % (GENERATED, today, ident['basename'], ident['sha'] or 'no git',
                                                   TOOL_VERSION)
    areas = assign_areas(sources, profile)
    for slug in [s for s, a in areas.items() if not a['files']]:
        report.warn('profile area %s matches no source file; it gets no leaf' % slug)
        del areas[slug]
    ctx = {'name': profile.get('name') or ident['name'], 'gen': gen, 'files': files, 'sources': sources,
           'facts': facts, 'areas': areas, 'profile': profile, 'selected': selected, 'identity': identity,
           'identity_notes': identity_notes, 'entries': entries,
           'surfaces': profile.get('surfaces', DEFAULT_SURFACES)}
    report.info('%s @ %s: %s, %s, %s' % (ident['basename'], ident['sha'] or 'no git', plural(len(files), 'file'),
                                         plural(len(sources), 'source file'), plural(len(areas), 'area')))

    rendered = render(ctx)
    produced = {}
    rows_live = []
    for base, leaves, purpose in rendered:
        produced.update(leaves)
        names = sorted(leaves, key=lambda fn: int(LEAF_RE.match(fn).group(2) or 1))
        parts = [(k, fn) for k, fn in enumerate(names, 1) if k > 1]
        rows_live.append((base, index_row(leaves[base][0], base, purpose, parts)))

    on_disk = {}
    if os.path.isdir(into):
        for fn in sorted(os.listdir(into)):
            if LEAF_RE.match(fn) and fn not in produced:
                on_disk[fn] = read_source(os.path.join(into, fn))
    idx_path = os.path.join(into, '.index.md')
    idx_text = read_source(idx_path) if os.path.isfile(idx_path) else None
    old_rows = {}
    for r in (current_rows(idx_text) if idx_text else None) or []:
        m = re.search(r'\]\(\./([^)]+)\)', r)
        if m:
            old_rows[m.group(1)] = r
    archived, stale, extra_parts = {}, {}, []
    for fn, text in on_disk.items():
        if LEAF_RE.match(fn).group(2):
            extra_parts.append(fn)
        elif any(ARCHIVED_RE.match(l) for l in text.split('\n')[:6]):
            archived[fn] = text
        else:
            stale[fn] = text
    rows = [r for _, r in rows_live]
    for fn in sorted(set(archived) | set(stale), key=byte_key):
        rows.append(old_rows.get(fn) if fn in archived and fn in old_rows
                    else index_row(h1_of(archived.get(fn) or stale[fn]) or fn, fn,
                                   'archived — the source no longer has this area', archived=True))
    if len(rows) > 15:
        report.warn('%d Contents rows: past the linter\'s 15; group areas in a profile' % len(rows))

    if args.check:
        drift = 0
        for fn in sorted(produced, key=byte_key):
            path = os.path.join(into, fn)
            if not os.path.isfile(path):
                report.fail('%s is missing' % fn)
                drift += 1
                continue
            diff = first_difference(read_source(path), produced[fn][1])
            if diff:
                report.fail('%s drifts: %s' % (fn, diff))
                drift += 1
        for fn in sorted(stale, key=byte_key):
            report.fail('%s is no longer produced and is not archived' % fn)
            drift += 1
        for fn in sorted(extra_parts, key=byte_key):
            report.fail('%s is a part the source no longer fills' % fn)
            drift += 1
        if idx_text is None:
            report.fail('.index.md is missing')
            drift += 1
        elif current_rows(idx_text) is None:
            report.fail('.index.md has no ## Contents section')
            drift += 1
        elif current_rows(idx_text) != rows:
            report.fail('.index.md Contents rows drift from the leaves')
            drift += 1
        if drift:
            print('== drift: %s; regenerate without --check ==' % plural(drift, 'finding'))
            return 1
        report.ok('no drift: %s and the Contents rows match the source' % plural(len(produced), 'leaf', 'leaves'))
        return 0

    if idx_text is not None and current_rows(idx_text) is None:
        raise Refusal('%s has no ## Contents section: nothing written' % idx_path)
    os.makedirs(into, exist_ok=True)
    written = 0
    for fn in sorted(produced, key=byte_key):
        path = os.path.join(into, fn)
        want = produced[fn][1]
        if os.path.isfile(path) and strip_generated(read_source(path)) == strip_generated(want):
            continue
        write(path, want)
        written += 1
    for fn, text in stale.items():
        write(os.path.join(into, fn), archived_stub(h1_of(text) or fn, today))
        report.info('%s archived: the source no longer has its area' % fn)
    for fn in extra_parts:
        os.remove(os.path.join(into, fn))
        report.info('%s removed: a continuation part the source no longer fills' % fn)
    new_idx = rewrite_index(idx_text if idx_text is not None else scaffold_index(ctx['name']), rows)
    if new_idx != idx_text:
        write(idx_path, new_idx)
    if not os.path.isfile(os.path.join(into, '.tags')):
        write(os.path.join(into, '.tags'), TAGS)
        report.info('.tags written (authored from now on)')
    if args.write_agent:
        write(os.path.join(into, '.agent'), agent_text(command_line(sys.argv[0], args)))
        report.info('.agent written')
    report.ok('%s rewritten, %s unchanged; %s' % (plural(written, 'leaf', 'leaves'),
                                                  plural(len(produced) - written, 'leaf', 'leaves'),
                                                  plural(len(rows), 'Contents row')))
    return 1 if report.fails else 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
